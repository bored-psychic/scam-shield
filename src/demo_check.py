import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
from shield import config
from shield.contracts import Effect, LEVEL_LABEL, Level
from shield.core.report import to_report
from shield.core.router import analyse
from shield.links.lexical import load_url_model
from shield.messages.text_head import load_text_model

# python src/demo_check.py   (from the project root; needs both models) -> reports/demo_check.md
# Runs the 14 illustrative demo messages (docs/demo/demo_set.json) through analyse() + to_report() exactly as the API does, with the default config
# (config.SAFETY_ADVICE_CAP as set), and records what comes out. Expected: a "scam" entry is at least Suspicious, a "genuine" entry is "No warning
# signs found". An entry that misses is RECORDED, not fixed: nothing here changes any detection code, and tests/test_demo.py locks the current levels.
# Every entry is illustrative (written for the demo, numbers and links fictional): CLAUDE.md rule 4, it never counts as real data.
DEMO_PATH = os.path.join(ROOT, "docs", "demo", "demo_set.json")
OUT_PATH = os.path.join(ROOT, "reports", "demo_check.md")
FLAGGED = (Level.SUSPICIOUS, Level.LIKELY_SCAM)
MAX_BLIPS = 4   # frontend/src/lib/evidence.ts MAX_BLIPS


def load_demo():
    with open(DEMO_PATH, encoding="utf-8") as f:
        return json.load(f)


def radar_tags(rep):
    """The radar's blips as the frontend draws them (blips() in frontend/src/lib/evidence.ts): danger / caution evidence, one per tag, at most 4, in the
    order rule.* -> link evidence -> tactic.* -> model.* -> rest; none on a no-warning verdict."""
    if rep.level == Level.NO_WARNING_SIGNS:
        return []
    rank = lambda e: 0 if e.id.startswith("rule.") else 2 if e.id.startswith("tactic.") else 3 if e.id.startswith("model.") else 4
    top = lambda g: [e for e in rep.evidence if rank(e) == g]
    ordered = top(0) + [e for c in rep.children for e in c.evidence] + top(2) + top(3) + top(4)
    tags = []
    for e in ordered:
        if e.effect in (Effect.DANGER, Effect.CAUTION) and e.tag not in tags:
            tags.append(e.tag)
    return tags[:MAX_BLIPS]


def judge(entry, rep):
    """PASS or MISS against the entry's expectation."""
    if entry["kind"] == "scam":
        ok = rep.level in FLAGGED
    else:
        ok = rep.level == Level.NO_WARNING_SIGNS
    return "PASS" if ok else "MISS"


def evaluate(entry, tm, um):
    rep = to_report(entry["text"], analyse(entry["text"], tm, um))
    return {"id": entry["id"], "kind": entry["kind"], "type": entry["type"], "text": entry["text"], "report": rep, "level": rep.level.value,
            "verdict": LEVEL_LABEL[rep.level], "tags": radar_tags(rep), "reasons": list(rep.reasons), "status": judge(entry, rep)}


def expected_label(kind):
    return "at least Suspicious" if kind == "scam" else LEVEL_LABEL[Level.NO_WARNING_SIGNS]


def main():
    entries = load_demo()
    tm, um = load_text_model(), load_url_model()
    rows = [evaluate(e, tm, um) for e in entries]
    n_pass = sum(r["status"] == "PASS" for r in rows)
    models = rows[0]["report"].meta.models
    L = ["# Demo check", "",
         "Generated by `python src/demo_check.py`. The 14 messages in `docs/demo/demo_set.json` go through `analyse()` + `to_report()` (Report v2), the same path the API uses.",
         "All 14 are **illustrative**: written for the demo, numbers and links fictional (CLAUDE.md rule 4: they never count as real data).",
         "A scam entry passes when the verdict is at least Suspicious; a genuine entry passes when it is *No warning signs found*. A MISS is recorded as it is: no detection code was changed to make an entry pass.",
         "Locked by `tests/test_demo.py`.", "",
         f"Models: text `{models['text']}`, url `{models['url']}`, gambling lookup `{models['gambling_lookup']}`. Safety-advice cap: {'ON' if config.SAFETY_ADVICE_CAP else 'OFF'} (default).", "",
         f"**{n_pass} of {len(rows)} pass.** Scam entries: {sum(r['status'] == 'PASS' for r in rows if r['kind'] == 'scam')} of {sum(r['kind'] == 'scam' for r in rows)} flagged. "
         f"Genuine entries: {sum(r['status'] == 'PASS' for r in rows if r['kind'] == 'genuine')} of {sum(r['kind'] == 'genuine' for r in rows)} left unflagged.", "",
         "| id | type | expected | actual verdict | radar tags | reasons | result |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['id']} | {r['type']} | {expected_label(r['kind'])} | {r['verdict']} | {', '.join(r['tags']) or '(none)'} | {'; '.join(r['reasons']) or '(none)'} | {r['status']} |")
    misses = [r for r in rows if r["status"] == "MISS"]
    L += ["", "## Misses", ""]
    if not misses:
        L.append("None.")
    for r in misses:
        rep = r["report"]
        what = "a scam left unflagged or under-called" if r["kind"] == "scam" else "a genuine message flagged"
        L += [f"- **{r['id']}** ({r['type']}): {what}. Verdict {r['verdict']}, text score {rep.meta.text_score}, link verdicts: "
              f"{', '.join(c.level.value for c in rep.children) or 'no links'}."]
    L += ["", "## Reading notes", "", "Written by hand on 2026-10-17 against the table above (commit 076c502; the d03 notes updated for rule R2 the same day); not generated and not checked by the test, so re-read them if the table changes.", "",
          "- A verdict of Likely scam can come from the text model alone (d03, d04, d07, d08: for d04, d07 and d08 there is no rule hit and no link verdict behind them, only wording cues and the text score; d03's rule guarantees only Suspicious), so a pass here is not a per-rule result.",
          "- d03 (\"enter your UPI PIN to receive the refund\"): the OTP / PIN / CVV rule does not fire ('enter' is not one of its verbs), but the PIN-to-receive rule (R2) does: receiving money never needs a PIN, so it adds its own red flag and guarantees at least Suspicious. The level did not change: Likely scam is still the text model's (score 0.916).",
          "- d10: the gambling lookup and the URL model both flag the link as Suspicious; the overall Likely scam comes from the text model's score. A gambling hit alone never gives Likely scam.",
          "- d09 is Suspicious, not Likely scam: the text score is 0.651, just under the Likely-scam cut-off 0.656 and above the Suspicious one 0.423; the OTP rule would also guarantee at least Suspicious.",
          "- g01 and g02 are genuine OTP warnings and pass with the safety-advice cap OFF; other genuine warnings can be flagged (reports/otp_advisory.md)."]
    L += ["", "## Per entry", ""]
    for r in rows:
        rep = r["report"]
        L += [f"### {r['id']} - {r['type']} ({r['kind']}) - {r['status']}", "", f"> {r['text']}", "",
              f"- Verdict: **{r['verdict']}** (text score {rep.meta.text_score}, thresholds {rep.meta.text_thresholds}; category {rep.category})",
              f"- Radar tags: {', '.join(r['tags']) or '(none)'}", f"- Reasons: {'; '.join(r['reasons']) or '(none)'}"]
        for c in rep.children:
            L.append(f"- Link: {c.level.value}; " + "; ".join(f"{e.id} [{e.effect.value}] \"{e.title}\"" for e in c.evidence))
        L.append("- Evidence: " + "; ".join(f"{e.id} [{e.effect.value}]" + (f" \"{e.quote}\"" if e.quote else "") for e in rep.evidence))
        L.append("")
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print(f"{n_pass}/{len(rows)} pass; wrote {os.path.relpath(OUT_PATH, ROOT)}")
    for r in rows:
        print(f"{r['status']:<4} {r['id']} {r['type']:<15} expected {expected_label(r['kind']):<22} actual {r['verdict']}")


if __name__ == "__main__":
    main()
