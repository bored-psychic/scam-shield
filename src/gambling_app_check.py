import json, os
import pandas as pd
import gambling_lists as gl
from shield.config import GAMBLING_DOMAINS_PATH, GAMBLING_INDIA_PATH
from shield.core.router import MAX_TEXT_CHARS, MAX_URLS
from shield.links.gambling import GAMBLING_NOT_GAMBLING, GAMBLING_PLATFORM_ROOTS, load_gambling
from shield.links.platforms import assess_link
from textprep import extract_urls

# What the gambling link rule (decision G1, src/shield/links/gambling.py) does to the app, measured on the lookup files and on the frozen
# splits. Run from the project root: python src/gambling_app_check.py   ->  reports/gambling_app_check.md
#   1. the lookup domains in the Tranco top 10k that were not hosting-platform roots: under G1 each one made a link Suspicious, whatever its
#      popularity, so this was the list for the user to review (okta.com is a login provider, not a casino). The user decided on 2026-10-17:
#      GAMBLING_PLATFORM_ROOTS (8, host-level only) and GAMBLING_NOT_GAMBLING (13) are exempt, the other 96 stay flagged; the "decision" column
#      shows it, and the script asserts that match() agrees with every row.
#   2. how many val and test messages contain a link that now matches, by basis. Counts only: no message text, no domain, is written.
# Nothing is fetched or resolved (CLAUDE.md rule 8); messages are only read, never used to fit anything (rule 1: the real test set is untouched).
TOP = 10_000
OUT = "reports/gambling_app_check.md"

D_ROOT, D_NOT, D_FLAG = "exempt: platform (host-level only)", "exempt: not gambling", "flagged (gambling operator / lottery)"
def decision(d):
    return D_ROOT if d in GAMBLING_PLATFORM_ROOTS else D_NOT if d in GAMBLING_NOT_GAMBLING else D_FLAG

lk = load_gambling()
look = pd.read_csv(GAMBLING_DOMAINS_PATH, sep="\t", dtype=str, keep_default_na=False)
look["rank"] = pd.to_numeric(look["tranco_rank"], errors="coerce")
top = look[look["rank"] <= TOP].sort_values("rank")
old_roots = lk.platform_suffixes - GAMBLING_PLATFORM_ROOTS   # the platform roots that existed before the review (wordpress.com ...)
top = top.assign(root=top["domain"].isin(old_roots), decision=[decision(d) for d in top["domain"]],
                 flagged=[(m := lk.match(f"https://{d}/")) is not None and m["basis"] == "list" for d in top["domain"]],
                 word=[gl.keyword_candidate(d) for d in top["domain"]])
review = top[~top["root"]]
assert (review["flagged"] == (review["decision"] == D_FLAG)).all(), "match() disagrees with the review decision for a top-10k domain"
assert GAMBLING_PLATFORM_ROOTS | GAMBLING_NOT_GAMBLING <= set(review["domain"]), "a reviewed domain is not in the top-10k review list"
n_root, n_not, n_flag = (int((review["decision"] == d).sum()) for d in (D_ROOT, D_NOT, D_FLAG))

# ---- messages: val and test only
msgs = pd.read_csv("data/final/messages.csv", usecols=["text", "text_hash", "label"])
sm = pd.read_csv("data/final/split_map.csv")
msgs = msgs.merge(sm, on="text_hash", validate="one_to_one")
msgs = msgs[msgs["split"].isin(["val", "test"])]
BASES = ["list", "platform_host", "india_token"]
def bases_of(text):
    """The bases of the gambling hits among the message's links, as analyse() would see them (same text cap, link cap, shorteners skipped)."""
    out = set()
    for u in extract_urls(text[:MAX_TEXT_CHARS], MAX_URLS):
        if (a := assess_link(u)) and a["kind"] == "shortener":
            continue
        if (m := lk.match(u)):
            out.add(m["basis"])
    return out
hits = [bases_of(t) for t in msgs["text"]]
msgs = msgs.assign(has_link=[bool(extract_urls(t[:MAX_TEXT_CHARS], 1)) for t in msgs["text"]], any=[bool(h) for h in hits],
                   **{b: [b in h for h in hits] for b in BASES})
rows = []
for split in ("val", "test"):
    for name, label in (("all", None), ("scam (label 1)", 1), ("benign (label 0)", 0)):
        d = msgs[msgs["split"] == split]
        d = d if label is None else d[d["label"] == label]
        rows.append((split, name, len(d), int(d["has_link"].sum()), int(d["any"].sum()), *[int(d[b].sum()) for b in BASES]))
table = ["| split | messages | total | with a link | with a gambling hit | list | platform_host | india_token |", "|---|---|---:|---:|---:|---:|---:|---:|"]
table += [f"| {s} | {n} | {t:,} | {w:,} | {a:,} | {x:,} | {y:,} | {z:,} |" for s, n, t, w, a, x, y, z in rows]

snap = json.load(open(GAMBLING_INDIA_PATH))["snapshot"]
fmt = lambda df: ["| domain | Tranco rank | lists | name has a gambling word | decision |", "|---|---:|---|---|---|"] + [
    f"| {r.domain} | {int(r.rank):,} | {r.lists or 'review sheet'} | {'yes' if r.word else 'no'} | {r.decision} |" for r in df.itertuples()]
md = [
    "# Gambling link rule (G1): what it flags\n",
    f"Generated by `src/gambling_app_check.py` from the lookup files built on the {snap} snapshots (`reports/gambling_lookup.md`). "
    "A gambling link is **Suspicious**, never Likely scam on its own; the lists are a gambling *category*, not a scam verdict. Strings only: nothing was fetched.\n",
    f"## 1. Lookup domains in the Tranco top {TOP:,}\n",
    f"- {len(top)} of the {len(look):,} lookup domains are in the Tranco top {TOP:,}: {int(top['root'].sum())} {'is a' if top['root'].sum() == 1 else 'are'} hosting-platform or shortener "
    f"root{'' if top['root'].sum() == 1 else 's'} from before the review (`{', '.join(top[top['root']]['domain'])}`), matched at host level only, and **{len(review)} were reviewed** below.",
    f"- **User decision 2026-10-17 on the {len(review)}: {n_root} hosting roots exempt (host-level only), {n_not} not gambling sites exempt, {n_flag} stay flagged.** "
    "The exempt domains are the constants `GAMBLING_PLATFORM_ROOTS` and `GAMBLING_NOT_GAMBLING` in `src/shield/links/gambling.py`; this script asserts that `match()` agrees with every row. "
    f"Under G1 *Tranco popularity never lowers a hit*, so a link to any of the **{n_flag} flagged domains** gets \"Suspicious - gambling or betting site\". "
    f"By name, {int(review['word'].sum())} of the {len(review)} look like gambling sites (a gambling word in the name, `gambling_lists.KW_RX` minus its look-alike list) and "
    f"{int((~review['word']).sum())} do not; the column was a hint for the review, not a decision.",
    f"- By list: {', '.join(f'{k} {v}' for k, v in review['lists'].replace('', 'review sheet').value_counts().items())}. "
    "Domains below the top 10k on the lists were not reviewed.\n",
    *fmt(review), "",
    f"## 2. Messages in the frozen val and test splits with a link that now matches\n",
    "Counts of messages, not links; a message with links of two bases counts under both bases and once under \"with a gambling hit\". "
    f"Links are found as `analyse()` finds them (first {MAX_TEXT_CHARS:,} characters, at most {MAX_URLS} links, shorteners skipped). "
    "No message text and no domain is written here. `test` is the frozen split, not the later real-message test set.\n",
    *table, "",
]
open(OUT, "w").write("\n".join(md))
print(f"top-10k lookup domains: {len(top)}; platform roots from before the review: {int(top['root'].sum())}; reviewed: {len(review)} = "
      f"{n_root} exempt platform (host-level only) / {n_not} exempt not gambling / {n_flag} flagged; wrote {OUT}")
print(f"val+test messages with a gambling hit: {int(msgs['any'].sum())} of {len(msgs):,}")
