"""Is a public "Indian SMS" dataset real, new and usable?  Synthetic / contamination audit (docs/plans/data_acquisition.md, section 4).

    .venv/bin/python src/audit_dataset.py                 # every dataset in DATASETS -> reports/dataset_audit.md
    .venv/bin/python src/audit_dataset.py --only otp_sms_preview

Measurement only: nothing is ingested, no model is scored, no network. Each dataset gets the same checks:
  1. template repetition: rows are grouped with the real-message intake's rule (src/intake_real.py: links -> <URL>, lower case, digit runs ->
     0, then src/neardup.py's near-duplicate test, Jaccard >= 0.7 on char 5-grams, raw or normalised view). Reported: exact-duplicate share,
     share of rows in a group of 2+, rows per group, the largest group's share.
  2. label balance (positive share) and whether it is suspiciously exact.
  3. distribution uniformity: category counts (max / min), message length spread (coefficient of variation), and the numbers in money amounts:
     share of amounts with a leading zero ("INR 040.27", a random-number generator's mark) and the first-digit distribution against Benford's
     law (mean absolute deviation; Nigrini's first-digit bands: > 0.015 = non-conforming), only with >= 100 amounts.
  4. provenance: what the dataset's own card / paper says about how it was collected (written in DATASETS by hand, with the URL).
  5. overlap with our train split: share of rows that are near-duplicates of a TRAIN row of data/final/messages.csv (intake_real.overlap_flags,
     the splits' rule, PII masks applied first). Not run for the controls, which are train rows.
  6. how Indian: share of rows with an Indian marker (rupee / Rs / INR, UPI, +91, an Indian bank / app / government brand, Aadhaar, PAN).
Controls with known answers run through the same checks so the thresholds below can be read against them: uci_sms_spam (real, UK /
Singapore SMS), india_fraud_final (85.5% generated templates), synth_india (all generated by src/synth_india.py). Control rows come from
messages.csv TRAIN and VAL only: test rows are dropped before any text is read (CLAUDE.md rule 1).

Reject rules (any one fails the dataset as REAL data; the reason is printed): no stated real collection (rule 4: unknown provenance never counts
as real); >= 1% of amounts with a leading zero; >= 10% of rows already near-duplicates of our train split (contamination: it is data we already
have, and its test-split twins would leak); category counts within 5% of each other over >= 4 categories (a generator's quota, not a natural
collection). Flags only (reported, never a reason on their own): exact 50/50 labels and heavy template repetition (real inboxes are templated
too: bank alerts, OTPs), and Benford MAD > 0.015. Benford is a flag because no real Indian control with >= 100 rupee amounts exists here (UCI
has 1), so the threshold is untested on real Indian SMS, where promo prices (99, 499) may break Benford by themselves.
Role in_use = already a training source of messages.csv (train + val rows loaded): overlap with train is trivially high and is not measured.
"""
import argparse, math, re, sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src")]
import pandas as pd
import realguard
from intake_real import make_groups, overlap_flags

MESSAGES = ROOT / "data" / "final" / "messages.csv"
REPORT = ROOT / "reports" / "dataset_audit.md"

# role: control_real / control_synthetic (known answers) or candidate. path None = rows of messages.csv with that source (train + val only).
DATASETS = [
    dict(name="uci_sms_spam", role="control_real", path=None, provenance="real: SMS Spam Collection v.1 (Almeida et al. 2011), collected from Grumbletext (UK), the NUS SMS Corpus (Singapore) and a PhD thesis; https://archive.ics.uci.edu/dataset/228/sms+spam+collection"),
    dict(name="india_fraud_final", role="control_synthetic", path=None, provenance="mostly generated: the file's own is_synthetic column marks 2,737 of 3,200 rows (85.5%) synthetic; data/sources.yaml"),
    dict(name="synth_india", role="control_synthetic", path=None, provenance="generated: src/synth_india.py templates (is_synthetic=True)"),
    dict(name="scam_ham_india", role="in_use", path=None, real_claim=False, provenance="unknown: a local CSV (text, label ham / spam) with no card, author or collection method (data/sources.yaml has none); already in training"),
    dict(name="otp_sms_preview", role="candidate", path=ROOT / "data/external/text/otp_sms_preview/otp_sms_preview_2026-10-07.csv",
         text="sms_text", label="is_phishing_original", positive={"true", "1"}, category="predicted_otp_intent", real_claim=False,
         provenance="mixed: the card says 'collected from real-world sources' plus LLM-labelled rows and synthetic augmentation (classification_status 'synthetic' "
                    "on 794 of the first 5,000 rows); no source licences, no collection method; https://huggingface.co/datasets/gandharvbakshi/SMS-dataset-sample-10k"),
    dict(name="mendeley_smishing", role="candidate", path=ROOT / "data/external/text/mendeley_smishing/Dataset_5971.csv", encoding="latin-1",
         text="TEXT", label="LABEL", positive={"smishing", "spam"}, real_claim=True,
         provenance="stated: 'collected by converting the images obtained from the Internet to text using Python code' (OCR), messages credited to T. A. Almeida "
                    "(UCI SMS Spam co-author) and G. Sonowal; Mishra & Soni, v1 2022-06-20, CC BY 4.0; https://data.mendeley.com/datasets/f45bkkt8pr/1"),
]

INDIAN_RX = re.compile(r"(?i)₹|\brs\.?\s?\d|\binr\b|\bupi\b|\+91|\b(?:sbi|hdfc|icici|axis|kotak|paytm|phonepe|bhim|npci|aadhaa?r|pan card|irctc|"
                       r"jio|airtel|vodafone|bsnl|lic|epfo|uidai|india post|flipkart|myntra|swiggy|zomato|meesho|ola|uber india|crore|lakh|"
                       r"income tax|gst|rbi|sebi|nse|bse|demat|kyc|fastag|ifsc|neft|imps|rtgs)\b")
AMOUNT_RX = re.compile(r"(?i)(?:₹|\brs\.?|\binr)\s*(\d[\d,]*(?:\.\d+)?)")
BENFORD = {d: math.log10(1 + 1 / d) for d in range(1, 10)}
MIN_AMOUNTS = 100
LEADING_ZERO_MAX, BENFORD_MAD_MAX, OVERLAP_MAX, EVEN_CATEGORIES = 0.01, 0.015, 0.10, 1.05


def load(spec):
    """-> DataFrame(text, label (0 / 1 / None), category)."""
    if spec["path"] is None:
        m = pd.read_csv(MESSAGES, usecols=["text", "label", "subcategory", "category", "source", "split"], low_memory=False, keep_default_na=False)
        m = m[(m["source"] == spec["name"]) & (m["split"] != "test")]   # test rows dropped before the text is used (rule 1)
        cat = m["subcategory"].where(m["subcategory"] != "", m["category"])
        return pd.DataFrame({"text": m["text"].astype(str), "label": m["label"].astype(int), "category": cat.astype(str)}).reset_index(drop=True)
    realguard.refuse_real_paths([spec["path"]])   # never audit the real test set or a probe as if it were a public dataset
    d = pd.read_csv(spec["path"], low_memory=False, keep_default_na=False, encoding=spec.get("encoding", "utf-8"))
    lab = d[spec["label"]].astype(str).str.strip().str.lower().isin(spec["positive"]).astype(int) if spec.get("label") else None
    return pd.DataFrame({"text": d[spec["text"]].astype(str), "label": lab, "category": d[spec["category"]].astype(str) if spec.get("category") else ""})


def template_stats(texts):
    recs = [{"masked": t} for t in texts]
    groups = make_groups(recs)
    sizes = sorted((len(v) for v in groups.values()), reverse=True)
    n = len(texts)
    return {"groups": len(sizes), "in_multi": sum(s for s in sizes if s > 1) / n, "rows_per_group": n / len(sizes), "largest": sizes[0] / n,
            "exact_dup": 1 - len({realguard.norm_key(t) for t in texts}) / n}


def amount_stats(texts):
    amts = [a.replace(",", "") for t in texts for a in AMOUNT_RX.findall(t)]
    lead0 = sum(len(a.split(".")[0]) > 1 and a.startswith("0") for a in amts)
    firsts = [next(c for c in a if c in "123456789") for a in amts if any(c in "123456789" for c in a)]
    mad = None
    if len(firsts) >= MIN_AMOUNTS:
        cnt = Counter(firsts)
        mad = sum(abs(cnt[str(d)] / len(firsts) - p) for d, p in BENFORD.items()) / 9
    return {"amounts": len(amts), "leading_zero": lead0 / len(amts) if amts else 0.0, "benford_mad": mad}


def audit(spec):
    d = load(spec)
    texts = d["text"].tolist()
    out = {"name": spec["name"], "role": spec["role"], "rows": len(d), "provenance": spec["provenance"]}
    out.update(template_stats(texts))
    out["positive"] = d["label"].mean() if d["label"] is not None else None
    cats = Counter(c for c in d["category"] if c)
    out["categories"] = len(cats)
    out["cat_ratio"] = max(cats.values()) / min(cats.values()) if len(cats) >= 2 else None
    lens = d["text"].str.len()
    out["len_cv"] = lens.std() / lens.mean()
    out.update(amount_stats(texts))
    out["indian"] = sum(bool(INDIAN_RX.search(t)) for t in texts) / len(texts)
    out["overlap"] = sum(overlap_flags(texts)) / len(texts) if spec["role"] == "candidate" else None
    reasons = []
    if spec["role"] == "in_use" and not spec.get("real_claim"):
        reasons.append("no stated real collection: cannot count as real (rule 4)")
    if spec["role"] == "candidate":
        if not spec.get("real_claim"):
            reasons.append("no stated real collection: cannot count as real (rule 4)")
        if out["amounts"] and out["leading_zero"] >= LEADING_ZERO_MAX:
            reasons.append(f"{out['leading_zero']:.1%} of amounts have a leading zero (machine-made numbers)")
        if out["overlap"] is not None and out["overlap"] >= OVERLAP_MAX:
            reasons.append(f"{out['overlap']:.1%} of rows are near-duplicates of our train split")
        if out["categories"] >= 4 and out["cat_ratio"] is not None and out["cat_ratio"] <= EVEN_CATEGORIES:
            reasons.append(f"{out['categories']} categories within {EVEN_CATEGORIES - 1:.0%} of each other (a generator's quota)")
    flags = []
    if out["positive"] is not None and out["rows"] >= 1000 and abs(out["positive"] - 0.5) < 0.005:
        flags.append("labels exactly 50/50")
    if out["rows_per_group"] >= 3:
        flags.append(f"{out['rows_per_group']:.1f} rows per template")
    if out["benford_mad"] is not None and out["benford_mad"] > BENFORD_MAD_MAX:
        flags.append(f"amount first digits off Benford (MAD {out['benford_mad']:.3f})")
    if spec["role"] == "in_use":
        out["verdict"] = "in training already; " + ("; ".join(reasons) if reasons else "provenance stated")
    else:
        out["verdict"] = ("REJECT: " + "; ".join(reasons)) if reasons else ("control" if spec["role"].startswith("control") else "pass")
    out["flags"] = "; ".join(flags)
    return out


def fmt(v, pct=False, nd=2):
    if v is None:
        return "n/a"
    return f"{v:.1%}" if pct else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))


def report(rows):
    lines = ["# Public dataset audit (synthetic / contamination)", "",
             "Written by `src/audit_dataset.py` (no network, nothing ingested). Method and reject rules: the script's docstring and "
             "`docs/plans/data_acquisition.md` section 4. Controls are train + val rows of `data/final/messages.csv` (test rows never read).", "",
             "| dataset | role | rows | exact dup | in a template group | rows / template | largest template | positive | categories (max/min) "
             "| length CV | amounts | leading-zero amounts | Benford MAD | Indian marker | overlap with train | verdict | flags |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['name']} | {r['role']} | {r['rows']} | {fmt(r['exact_dup'], True)} | {fmt(r['in_multi'], True)} | {fmt(r['rows_per_group'])} "
                     f"| {fmt(r['largest'], True)} | {fmt(r['positive'], True)} | {r['categories']} ({fmt(r['cat_ratio'])}) | {fmt(r['len_cv'])} | {r['amounts']} "
                     f"| {fmt(r['leading_zero'], True)} | {fmt(r['benford_mad'], nd=3)} | {fmt(r['indian'], True)} | {fmt(r['overlap'], True)} | {r['verdict']} | {r['flags']} |")
    lines += ["", "## Provenance as stated", ""] + [f"- **{r['name']}**: {r['provenance']}" for r in rows]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*", help="dataset names from DATASETS")
    ap.add_argument("--report", default=str(REPORT))
    a = ap.parse_args()
    rows = []
    for spec in DATASETS:
        if a.only and spec["name"] not in a.only:
            continue
        r = audit(spec)
        print(f"{r['name']}: {r['rows']} rows, {r['in_multi']:.1%} in template groups, overlap {fmt(r['overlap'], True)} -> {r['verdict']}")
        rows.append(r)
    Path(a.report).write_text(report(rows), encoding="utf-8")
    print(f"wrote {a.report}")


if __name__ == "__main__":
    main()
