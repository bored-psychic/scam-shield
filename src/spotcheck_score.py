import argparse
import csv
import hashlib
import math
import re
import sys
from pathlib import Path

# Scores a native-speaker spot-check of the machine translations: the reviewer's export (docs/spotcheck/*.txt) joined to the
# sampled rows (reports/spotcheck_<code>.csv, written once by `translate_parents.py finalise` and committed; this script never
# resamples). Nothing under data/ is read or written.
# Export format: first line "SCAMSHIELD-SPOTCHECK-<CODE> v<N>", then one line per row: id|meaning_same|label_still_right|formal|notes
#   meaning_same / label_still_right are y or n, formal is "formal" or empty, notes is free text. Sheet rows the reviewer did not
#   answer are listed, not scored; an id that is not in the sheet is an error.
# Output: per-question counts with Wilson 95% intervals, the same counts by label (the sheet is 25 benign + 25 scam, not the mix of
# the kept pool), the CLAUDE.md acceptance gate, and a table of every row with an n. The sheet picks the language, so the Kannada
# export runs through the same code.
#   python src/spotcheck_score.py                                           (Hindi; stdout is ASCII-escaped)
#   python src/spotcheck_score.py --update-report reports/spotcheck_hi.md   (rewrites only the block between the markers, UTF-8)
Z = 1.959964  # two-sided 95%
GATE = 0.90   # CLAUDE.md: accept a language at >= 90% y on both columns
BEGIN = "<!-- BEGIN generated by src/spotcheck_score.py -->"
END = "<!-- END generated by src/spotcheck_score.py -->"


def wilson(k, n, z=Z):
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def parse_export(path):
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    m = re.fullmatch(r"SCAMSHIELD-SPOTCHECK-([A-Z]{2}) v(\d+)", lines[0].strip()) if lines else None
    if not m:
        sys.exit(f"{path}: the first line must be 'SCAMSHIELD-SPOTCHECK-<CODE> v<N>'")
    code, answers = m.group(1).lower(), {}
    for no, line in enumerate(lines[1:], 2):
        if not line.strip():
            continue
        f = line.split("|", 4)  # notes is last, so a '|' inside it cannot add a field
        if len(f) != 5:
            sys.exit(f"{path}:{no}: expected id|meaning_same|label_still_right|formal|notes, got {line!r}")
        rid, q1, q2, formal, notes = f
        if not re.fullmatch(code + r"\d\d", rid):
            sys.exit(f"{path}:{no}: id {rid!r} is not {code}NN")
        if q1 not in ("y", "n") or q2 not in ("y", "n") or formal not in ("", "formal"):
            sys.exit(f"{path}:{no}: meaning_same and label_still_right must be y or n and formal must be empty or 'formal': {line!r}")
        if rid in answers:
            sys.exit(f"{path}:{no}: {rid} appears twice")
        answers[rid] = {"meaning": q1 == "y", "label_ok": q2 == "y", "formal": formal == "formal", "notes": notes}
    if not answers:
        sys.exit(f"{path}: no answers")
    return code, m.group(2), answers


def load_rows(path):
    with open(path, encoding="utf-8-sig", newline="") as fh:
        rows = {r["row_id"]: r for r in csv.DictReader(fh)}
    need = {"label", "parent_source", "english_parent", "translation"}
    if not rows or not need <= set(next(iter(rows.values()))):
        sys.exit(f"{path}: expected the columns row_id, label, parent_source, english_parent, translation")
    return rows


def pct(x):
    return f"{100 * x:.1f}%"


def cell(text):
    return text.replace("|", "\\|").replace("\r", "").replace("\n", "<br>").strip()


def render(export, rows_path, code, version, answers, rows):
    unknown = sorted(set(answers) - set(rows))
    if unknown:
        sys.exit(f"ids in the export but not in {rows_path}: {unknown}")
    ids = sorted(answers)
    n = len(ids)
    qs = (("Q1 meaning the same", "meaning"), ("Q2 label still right", "label_ok"), ("Formal (flagged by the reviewer)", "formal"))
    L = [BEGIN, "",
         f"Inputs: `{export}` (v{version}, sha256 `{sha256(export)}`) joined to `{rows_path}` (sha256 `{sha256(rows_path)}`) on the row id.", ""]
    miss = sorted(set(rows) - set(answers))
    by = lambda lab: sum(1 for i in ids if rows[i]["label"] == lab)
    missing = ", ".join(i + " (" + rows[i]["label"] + ")" for i in miss)
    L.append(f"Rows answered: {n} of {len(rows)} ({by('scam')} scam, {by('benign')} benign)."
             + (f" Not answered, so not scored: {missing}." if miss else ""))
    L += ["", "| Question | Count | Rate | Wilson 95% CI | Gate: >= 90% y |", "|---|---|---|---|---|"]
    gate = []
    for name, key in qs:
        k = sum(answers[i][key] for i in ids)
        lo, hi = wilson(k, n)
        if key == "formal":
            g = "-"
        else:
            gate.append(k / n >= GATE)
            g = f"point estimate {'met' if k / n >= GATE else 'not met'}; lower bound {'met' if lo >= GATE else 'not met'}"
        L.append(f"| {name} | {k}/{n} | {pct(k / n)} | {pct(lo)} to {pct(hi)} | {g} |")
    L += ["", f"CLAUDE.md gate (>= {GATE:.0%} y on both questions, point estimate): **{'met' if all(gate) else 'not met'}**.", "",
          "By label (counts only; the sheet holds 25 scam + 25 benign, the kept translations are about 15% scam):", "",
          "| Label | Rows | Q1 meaning | Q2 label | Formal |", "|---|---|---|---|---|"]
    for lab in ("scam", "benign"):
        s = [i for i in ids if rows[i]["label"] == lab]
        if s:
            L.append(f"| {lab} | {len(s)} | " + " | ".join(f"{sum(answers[i][key] for i in s)}/{len(s)}" for _, key in qs) + " |")
    L += ["", "By parent source (the sheet has no shorthand-versus-sentence column; the source is the nearest proxy):", "",
          "| Parent source | Rows | Q1 meaning | Q2 label | Formal |", "|---|---|---|---|---|"]
    for src in sorted({rows[i]["parent_source"] for i in ids}):
        s = [i for i in ids if rows[i]["parent_source"] == src]
        L.append(f"| {src} | {len(s)} | " + " | ".join(f"{sum(answers[i][key] for i in s)}/{len(s)}" for _, key in qs) + " |")
    bad = [i for i in ids if not (answers[i]["meaning"] and answers[i]["label_ok"])]
    L += ["", f"Rows with an n ({len(bad)}):", ""]
    if bad:
        L += ["| id | Label | Source | Fails | English parent | Translation | Reviewer notes |", "|---|---|---|---|---|---|---|"]
        for i in bad:
            a, r = answers[i], rows[i]
            fails = " + ".join(q for q, ok in (("Q1 meaning", a["meaning"]), ("Q2 label", a["label_ok"])) if not ok)
            L.append(f"| {i} | {r['label']} | {r['parent_source']} | {fails} | {cell(r['english_parent'])} | {cell(r['translation'])} | {cell(a['notes'])} |")
    L += ["", END]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description="Score a native-speaker spot-check export against the sampled rows.")
    ap.add_argument("--export", default="docs/spotcheck/hi_friend_v1.txt")
    ap.add_argument("--rows", help="default: reports/spotcheck_<code>.csv, the code taken from the export header")
    ap.add_argument("--update-report", metavar="MD", help="rewrite the generated block of this report (UTF-8); stdout is unchanged")
    a = ap.parse_args()
    code, version, answers = parse_export(a.export)
    rows_path = a.rows or f"reports/spotcheck_{code}.csv"
    text = render(a.export, rows_path, code, version, answers, load_rows(rows_path))
    print(text.encode("ascii", "backslashreplace").decode("ascii"))  # Hindi / Kannada stay escaped on the terminal
    if a.update_report:
        p = Path(a.update_report)
        old = p.read_text(encoding="utf-8")
        i, j = old.find(BEGIN), old.find(END)
        if i < 0 or j < i:
            sys.exit(f"{p}: the markers {BEGIN!r} and {END!r} are missing")
        p.write_text(old[:i] + text + old[j + len(END):], encoding="utf-8")
        print(f"\nupdated {p}")


if __name__ == "__main__":
    main()
