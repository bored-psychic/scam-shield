import os, sys
import joblib
import numpy as np
import pandas as pd
from url_features import host_row

# Shortcut check for the gambling_spam class -> reports/gambling_url_head.md. Nothing is retrained: the saved host-only URL head
# (models/url_head.joblib, trained before this class existed) is only asked what it does with the new rows, which it never saw
# (the 80 relabelled rows were in its training set as benign, so they are left out). Strings only (CLAUDE.md rule 8).
#   python src/gambling_report.py        (after build_urls.py)
df = pd.read_csv("data/final/urls.csv", low_memory=False)
b = joblib.load("models/url_head.joblib")
model, feats, top_tld, FLAG, HIGH = b["model"], b["features"], b["top_tld"], b["threshold"], b["threshold_high"]

new = df[df["source"] == "ut1_blp_gambling"].copy()
rows = [host_row("https://" + d, top_tld) for d in new["reg_domain"]]
ok = [i for i, r in enumerate(rows) if r is not None]
new = new.iloc[ok].copy()
new["score"] = model.predict_proba(pd.DataFrame([rows[i] for i in ok])[feats])[:, 1]
tld = new["reg_domain"].str.rsplit(".", n=1).str[-1]
new["group"] = np.where(tld.isin(["bet", "casino"]), ".bet / .casino", np.where(tld.isin(["com", "in"]), ".com / .in", "other TLD"))
new["flag"], new["high"] = new["score"] >= FLAG, new["score"] >= HIGH

pred = pd.read_csv("data/final/url_preds.csv")   # written by the last url_head.py run (before this class): the benign reference
ref = pred[(pred["label"] == "benign") & (pred["task"] == "phishing_vs_benign") & pred["split"].isin(["val", "test"])]
ref_flag, ref_high = float((ref["score_host"] >= FLAG).mean()), float((ref["score_host"] >= HIGH).mean())

def pct(x):
    return f"{100 * x:.1f}%"
def table(headers, rows):
    return "\n".join(["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)] + ["| " + " | ".join(map(str, r)) + " |" for r in rows])

g = new.groupby("group").agg(n=("score", "size"), flag=("flag", "mean"), high=("high", "mean"), median=("score", "median"))
by_split = new.groupby("split", observed=True).agg(n=("score", "size"), flag=("flag", "mean"))
dom = df[df["label"].isin(["benign", "phishing", "gambling_spam"])].copy()
dom["sub"] = dom["host"].str.count(r"\.") + 1 - dom["reg_domain"].str.count(r"\.") - 1
dom["host_len"] = dom["host"].str.len()
dom["n_hyph"] = dom["host"].str.count("-")
dom["n_dig"] = dom["host"].str.count(r"\d")
shape = dom.groupby("label").agg(rows=("host", "size"), with_subdomain=("sub", lambda s: (s > 0).mean()), median_host_len=("host_len", "median"),
                                 hyphen_share=("n_hyph", lambda s: (s > 0).mean()), digit_share=("n_dig", lambda s: (s > 0).mean()))
md = [
    "# gambling_spam and the existing URL head\n",
    "Generated by `src/gambling_report.py`. The URL head was **not retrained**; this is what the saved host-only head "
    f"(`models/url_head.joblib`: flag {FLAG:.3f}, Likely scam {HIGH:.3f}) does on the {len(new):,} new gambling_spam rows, which it never saw. "
    "gambling_spam is a category (licensed operators are on both lists), so a flag here is not a defect.\n",
    f"Reference: on benign val + test rows the same head flags {pct(ref_flag)} and reaches Likely scam on {pct(ref_high)}.\n",
    "## Flag rate by TLD group (new rows, both-lists domains)\n",
    table(["TLD group", "n", f"flagged (>= {FLAG:.3f})", f"Likely scam (>= {HIGH:.3f})", "median score"],
          [(k, f"{int(r.n):,}", pct(r.flag), pct(r.high), f"{r['median']:.3f}") for k, r in g.iterrows()]),
    "\nBy split: " + ", ".join(f"{k} {pct(r.flag)} of {int(r.n):,}" for k, r in by_split.iterrows()) + ".\n",
    "## Shortcuts a retrain would learn (host-only features)\n",
    table(["label", "rows", "has a subdomain", "median host length", "has a hyphen", "has a digit"],
          [(k, f"{int(r.rows):,}", pct(r.with_subdomain), int(r.median_host_len), pct(r.hyphen_share), pct(r.digit_share)) for k, r in shape.iterrows()]),
    "\n- **Subdomain depth / `n_labels`:** every gambling_spam row is a bare registered domain (like the Tranco benign rows), while a large share of "
    "phishing and ealvaradob-benign rows carry subdomains. A head trained on this would read depth and label count as class cues.",
    f"- **TLD:** `.bet` and `.casino` are {pct(float((tld.isin(['bet', 'casino'])).mean()))} of the new gambling_spam rows and almost absent from every other label "
    "(`reports/urls_gambling.md`); `tld_code` is already the head's strongest feature (BUGS.md).",
    "- **Hyphens and digits:** gambling_spam hosts look like phishing hosts on these (compare the rows above; names such as bet365, 1xbet, 777slots), "
    "which is why the existing head flags about half of them. A gambling-vs-benign head would partly learn \"digits and hyphens\".",
    "- **Length:** median host length sits between benign and phishing; check `host_len`, `reg_label_len` and entropy ablations before trusting a new head.\n",
]
open("reports/gambling_url_head.md", "w").write("\n".join(md))
print("\n".join(md[:12]))
print("wrote reports/gambling_url_head.md")
