"""False-alarm scan of the exact-brand-name rule R10 (decision C3, shield.links.lookalike.exact_brand): which Tranco domains does it fire on?
Pure string work on files on disk, no network (a domain is only ever a string here):

    .venv/bin/python scripts/exact_brand_scan.py            # writes reports/exact_brand_scan.md

Scans (1) the 200 benign domains of the 2026-10-22 live evaluation, (2) the Tranco top 10k, (3) the Tranco top 100k (extra: the R4 rule exempts that range because
owned-domain lists are incomplete; R10 has no such exemption, so this shows how complete the official lists are). Every hit is printed with its rank and brand.
"""
import csv, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src")]
from shield.config import LINKLISTS_DIR
from shield.links.lookalike import exact_brand, link_domain, reference

def refang(s):
    return re.sub(r"\bhxxp", "http", s, flags=re.I).replace("[.]", ".")

def hits_in(domains):
    out = []
    for rank, d in domains:
        host, reg = link_domain(f"https://{d}/")
        if (x := exact_brand(host, reg)):
            out.append((rank, d, x["brand"], x["label"]))
    return out

def tranco(limit):
    with open(LINKLISTS_DIR / "tranco_top1m.csv", encoding="utf-8") as f:
        for line in f:
            r, d = line.strip().split(",", 1)
            if int(r) > limit:
                break
            yield int(r), d

def benign_200():
    with open(ROOT / "data" / "eval_live" / "benign_2026-10-22.csv", encoding="utf-8") as f:
        return [(int(r["tranco_rank"]), refang(r["reg_domain_defanged"])) for r in csv.DictReader(f)]

def scan():
    sets = {"the 200 benign eval domains": benign_200(), "Tranco top 10k": list(tranco(10_000)), "Tranco top 100k": list(tranco(100_000))}
    return {k: (len(v), hits_in(v)) for k, v in sets.items()}

def main():
    res = scan()
    n_labels = len(reference()["exact"])
    L = ["# Exact-brand rule R10: false-alarm scan\n",
         f"Rule: `shield.links.lookalike.exact_brand` over `src/shield/links/exact_brands.json` ({n_labels} brand labels). String matching on files on disk; no network. Generated by `scripts/exact_brand_scan.py`.\n"]
    for k, (n, hits) in res.items():
        L.append(f"## {k} ({n:,} domains): {len(hits)} hit(s)\n")
        if hits:
            L += ["| Tranco rank | Domain | Brand named | Label |", "|---:|---|---|---|"] + [f"| {r} | `{d.replace('.', '[.]')}` | {b} | {lab} |" for r, d, b, lab in hits] + [""]
    L.append("## Reading the hits\n\nThe Tranco top 10k scan had one hit on the first run, `amazon[.]dev` (rank 133), Amazon's own developer site: added to Amazon's official list, as were `amazon.eu`, `amazon.jp`, "
             "`amazon.science`, `bankofbaroda.co.in` and `paytm.me` (found by the 100k scan; marked \"added after the scan\" in `exact_brands.json`, recognised by the author, ownership not re-checked). "
             "The hits that remain in the top 100k are other TLDs of Roblox, Zomato, Blinkit and BharatPe, and `amazon.work`. Whether they are the brand's own defensive registrations or someone else's cannot be told "
             "from the name, and checking needs a registry look-up (a network call), so they are left flagged: the effect is a Suspicious flag with the sentence \"Uses the name X but is not X's official website\" on a link to such "
             "a domain, and the fix for a confirmed one is a line in the brand's official list.\n")
    (ROOT / "reports" / "exact_brand_scan.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    for k, (n, hits) in res.items():
        print(f"{k}: {len(hits)} hits of {n}")
        for h in hits:
            print("   ", h)

if __name__ == "__main__":
    main()
